// Países más frecuentes en Kynea (Perú, Latinoamérica y principales de habla hispana)
export const POPULAR_COUNTRY_CODES = [
  'PE', 'CO', 'CL', 'AR', 'MX', 'VE', 'EC', 'BO', 'ES', 'US'
] as const;

export const POPULAR_COUNTRIES: Country[] = POPULAR_COUNTRY_CODES
  .map(code => COUNTRIES.find(c => c.code === code))
  .filter((c): c is Country => Boolean(c));

/**
 * Normaliza texto para búsqueda: minúsculas, sin acentos ni diacríticos.
 */
export function normalizeSearchText(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim();
}

/**
 * Busca un país por su nombre exacto o normalizado.
 */
export function findCountryByName(name: string | null | undefined): Country | undefined {
  if (!name) return undefined;
  const target = normalizeSearchText(name);
  return COUNTRIES.find(c => normalizeSearchText(c.name) === target);
}

/**
 * Busca un país por su código ISO alpha-2.
 */
export function findCountryByCode(code: string | null | undefined): Country | undefined {
  if (!code) return undefined;
  const upper = code.toUpperCase().trim();
  return COUNTRIES.find(c => c.code === upper);
}

const ALL_DIAL_CODES_BY_LENGTH = Array.from(
  new Set(COUNTRIES.map(c => c.dialCode))
).sort((a, b) => b.length - a.length);

/**
 * Parsea un número con prefijo internacional extrayendo el dialCode y el número local.
 */
export function parsePhonePrefix(phone: string | null | undefined): { code: string; number: string } {
  const raw = phone?.trim() ?? '';
  if (!raw) return { code: '+51', number: '' };
  for (const code of ALL_DIAL_CODES_BY_LENGTH) {
    if (raw.startsWith(code)) {
      return { code, number: raw.slice(code.length).trim() };
    }
  }
  return { code: '+51', number: raw.replace(/\D/g, '') };
}

